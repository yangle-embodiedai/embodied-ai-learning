# qa.py：跨行问答程序
# 问 4 个问题，用 f-string 拼出一段定制回复。
# 这是 Day 3 的核心产出，把"字符串方法 + input + 类型转换 + f-string"组合起来。

# ===== 1. 提问（input 依次阻塞等待，一次问一个）=====
# .strip() 去掉用户输入两端的空格，防止"  Yangle"这种带空格的输入污染后面的判断
name = input("1. 你叫什么？").strip()          # 存名字，str 型
hours = input("2. 每周能投入多少小时？").strip()  # 存小时数，此时还是 str
field = input("3. 最想去的公司类型？（整机/零部件/数据/租赁）").strip()  # 存方向，str 型
started = input("4. 开始投递了吗？（是/否）").strip()  # 存是否投递，str 型

# ===== 2. 类型转换 =====
# input() 返回值永远是 str，要参与算术必须先 int()
# 但用户可能乱敲（比如"二十"、空着回车），int() 会直接崩。
# 今天先不处理异常输入（那是第 5 天 if 判断的内容），默认你按格式输入。
hours_num = int(hours)          # "20" → 20，int 型，才能做乘法

# ===== 3. 用 f-string 拼出回复 =====
# f 前缀 + {表达式}：{} 里可以直接写变量名和运算，自动转成字符串
print()
print(f"你好 {name}")
# {hours_num} 是变量，{hours_num * 52} 是乘法运算，都能直接放进 {}
print(f"按每周 {hours_num} 小时算，到 2027-01-31 还有约 108 天，可投入约 {round(108 / 7 * hours_num)} 小时。")
# .lower() 把 field 转小写，统一大小写，方便后面比对（中文不受影响，但英文字符会变小）
# 这里 field 是中文，lower() 不改变内容，只是养成"清洗用户输入"的习惯
print(f"你关注的是【{field}】方向。")

# ===== 4. 按方向给一句判断 =====
# 这是明天的 if/elif 的简化版：用字典（dict）查表，代替一堆 if
# dict 查表比 if 链更简洁，改配置只改这一处
advice = {
    "整机": "整机是资本风口，但岗位少、门槛高，零基础进去多为测试或组装岗。",
    "零部件": "零部件是 2026 年资金流向，岗位多，但对机械/材料背景有要求。",
    "数据": "数据采集与标注对零基础最友好，且能直接接触行业核心数据。",
    "租赁": "RaaS 租赁模式兴起，适合有销售/运营经验的人切入。",
}
# dict 的 .get(键, 默认值)：如果用户输的字不在字典里，返回默认值，不会报 KeyError
print(advice.get(field, "这个方向我还不够了解，建议先从数据采集切进去。"))

# ===== 5. 投递状态判断 =====
# started 现在是 str，"是" 或 "否"
# 注意：这里用 == 比较，明天会用 if/elif 写成分档建议
if started == "是":
    print("已经在投递了，保持节奏，每周复盘一次。")
else:
    print("还没开始投递——这是本周最该补上的事。")

print()
print("=== qa.py 运行结束 ===")
