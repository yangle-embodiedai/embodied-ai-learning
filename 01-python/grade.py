# grade.py：成绩等级判断
# 输入分数，输出等级 A/B/C/D；对非法输入（超范围、负数、非数字）给出提示。
# 这是 Day 4 第 2 步：把 if/elif/else 和 Day 3 的字符串方法组合起来。

# ===== 1. 接收输入 =====
# input() 返回 str；.strip() 去掉两端空格，防止 " 85 " 这种输入干扰后面判断
raw = input("请输入分数(0-100):").strip()

# ===== 2. 分流：先判断"输入是什么"，再判断"分数是多少" =====
# 这里用了 Day 3 学的两个字符串方法：
#   .isdigit()   —— 字符串是否全部由数字 0-9 组成（"85" → True；"abc"、"-5"、"8.5" → False）
#   .startswith()—— 字符串是否以指定字符开头（"-5" 以 "-" 开头 → True）

if raw.isdigit():
    # 分支 A：纯数字。但 "105" 也是纯数字，所以还要再判断范围
    score = int(raw)               # 把 str 转成 int，才能做大小比较

    if score > 100:
        # 子分支 A1：纯数字但超过 100
        print("分数不能超过 100")
    elif score >= 90:
        print("等级 A")             # 90-100
    elif score >= 80:
        print("等级 B")             # 80-89
    elif score >= 60:
        print("等级 C")             # 60-79
    else:
        print("等级 D")             # 0-59

elif raw.startswith("-") and raw[1:].isdigit():
    # 分支 B：负数。结构是"以 - 开头 + 后面是纯数字"
    # raw[1:] 是切片：从第 1 位取到末尾，即去掉负号后的部分（Day 3 的切片知识）
    # 为什么要拆开判断？因为 "-5".isdigit() 是 False（负号不算数字），
    # 不拆开的话负数会被误判成"非数字"，无法给出"不能为负"的精确提示
    print("分数不能为负数")

else:
    # 分支 C：既不是纯数字、也不是负数 → 真正的非数字输入
    # 例：abc、8.5（小数点不算数字）、空字符串（直接回车）
    print("请输入 0-100 的整数，例如 85")

# ===== 3. 边界值说明（测试时重点验证）=====
# 90 → A（>=90 含 90 本身）；89 → B；60 → C；59 → D
# "含起不含止"在等级里的体现：90 归 A 不归 B，因为条件是 >= 90
