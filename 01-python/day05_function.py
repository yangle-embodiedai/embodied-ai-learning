# ============ 概念速记（30 秒过一遍）============
# - def 定义函数：def 函数名(参数):  函数体要缩进 4 空格
# - 参数：函数名括号里的变量，调用时传进去的值
# - 返回值：函数体里 return 后面跟的值，没有 return 默认返回 None
# - 调用：函数名(实参)，写在小括号里，不是写在 def 那行

# ============ 示例 1：最简函数 ============
def greet():
    # 函数体：打印一句问候（没有参数、没有返回值）
    print("你好，白杨")

# 调用示例 1（执行时屏幕输出：你好，白杨）
greet()


# ============ 示例 2：带参数 + 带返回值 ============
def add(a, b):
    # a、b 是参数（形参），调用时传进来的实参会赋给它们
    return a + b  # 把和返回给调用者

# 调用并把返回值存进变量
result = add(3, 4)
print(result)  # 输出：7

# 也可以用函数返回参与表达式
print(add(10, 20) * 2)  # 输出：60


# ============ 示例 3：默认参数 ============
def describe(name, city="深圳"):
    # city 有默认值"深圳"，调用时不传 city 就用默认
    print(f"{name} 在 {city}")

describe("白杨")        # 输出：白杨 在 深圳
describe("老杨", "杭州")  # 输出：老杨 在 杭州


