# ===== 2.1 六种基本类型 =====
# 变量 = 一个名字绑定到一个值。下面的 name、hours 都是名字。
name = "杨乐"
#   变量名 name（不能以数字开头，不能用空格）
#   = 赋值运算符，把右边的值"绑定"给左边的名字
#   "杨乐" 是字符串 str，双引号包裹

hours_per_week = 20
#   整数 int，不带引号、不带小数点。20 就是 20，不是 "20"

completion_rate = 0.35
#   浮点数 float，带小数点。0.35 表示 35%

is_employed = True
#   布尔 bool，只有两个值：True / False。注意首字母必须大写，true（小写）会报错

companies = ["优必选", "乐聚", "星尘智能"]
#   列表 list，方括号 [ ] 包裹，逗号 , 分隔。有序，下标从 0 开始
#   companies[0] 就是 "优必选"

company = {"name": "优必选", "city": "深圳", "listed": True}
#   字典 dict，花括号 { } 包裹，内部是 "键": 值 对，冒号 : 分隔
#   company["name"] 就是 "优必选"，company["city"] 就是 "深圳"

# ===== 2.2 类型决定运算规则（今天最核心的坑）=====
print(20 * 52)        # int 乘法 → 1040
print("20" * 52)      # str 重复 52 次 → "20202020..."
# 同一对 * 号，左边是 int 就乘，左边是 str 就重复。
# 这是新手最容易被坑的地方：算出"一年可投入 20202020 小时"且完全不报错。

print(20 + 30)        # int 加法 → 50
print("20" + "30")    # str 拼接 → "2030"（把两段文字连起来）
# 下面这行会直接崩溃，跑一下看报错信息：
# print(20 + "30")    # TypeError: 不能把 int 和 str 相加

# ===== 2.3 类型转换 =====
# 把字符串变成 int，再做算术
print(int("20") * 52)   # 先把 "20" 转成 20，再乘 52 → 1040

# 把数字变成 str，再拼接
print("剩余 " + str(109) + " 天")   # 109 必须转 str 才能和文字拼 → "剩余 109 天"

# ===== 2.4 运算符 =====
print(109 / 7)    # 除号 / 永远返回 float → 15.571428...
print(109 // 7)   # 两个 // 是整除，向下取整 → 15
print(109 % 7)    # % 是取余（mod），109 除以 7 的余数 → 4
print(2 ** 10)    # 两个 ** 是幂，2 的 10 次方 → 1024

