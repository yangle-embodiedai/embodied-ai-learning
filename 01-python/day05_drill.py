# day05_drill.py：for 循环入门 + 九九乘法表
# 新概念：for / range() / 循环嵌套 / print 的 end 参数
# 跑法：VS Code 打开 → Ctrl+S → Ctrl+F5（本文件没有 input，直接出结果）

# ===== 1. for 循环：遍历 =====
# 定义：for 变量 in 序列:  依次把序列里的每个元素赋给变量，执行一次缩进块。
# 序列取完，循环结束。和 while 的区别：while 靠条件决定要不要继续，
# for 靠"序列有多少个元素"决定循环几次——次数是确定的就用 for。

for name in ["优必选", "乐聚", "星尘智能"]:     # 遍历 list：每次拿出一个元素
    print(name)                                # 打印 3 次，name 依次是三个公司名

# ===== 2. range()：生成整数序列 =====
# 定义：range(起, 止, 步) 生成"从起到止-1"的整数序列——**含起不含止**，和切片规则一致！
print(list(range(1, 5)))      # [1, 2, 3, 4]  ← 不含 5
print(list(range(5)))         # [0, 1, 2, 3, 4]  ← 只给一个数 = 从 0 数到它-1
print(list(range(1, 10, 2)))  # [1, 3, 5, 7, 9]  ← 步长 2，和切片的步长同理
# 注意：range 本身不是列表，是"惰性序列"（用到才生成），套 list() 是为了打印出来看

for i in range(1, 6):         # i 依次是 1,2,3,4,5
    print(f"第 {i} 天")        # 循环 5 次

# ===== 3. 循环嵌套：外层走 1 步，内层走完一整圈 =====
# 打印 3×3 的位置表，观察执行顺序
for i in range(1, 4):             # 外层：i = 1,2,3
    for j in range(1, 4):         # 内层：对每个 i，j 都完整走 1,2,3
        print(f"({i},{j})", end=" ")   # end=" "：本行不打换行，改打空格，让结果排成一行
    print()                       # 内层走完一行后，print() 空参 = 只打一个换行
# 输出三行：(1,1) (1,2) (1,3) / (2,1) ... / (3,1) ...
# end 参数：print 默认每次结尾打 \n（换行），end=" " 把它换成了空格

# ===== 4. 九九乘法表（本文件目标产出）=====a
# 结构分析：第 i 行有 i 个式子（第 1 行 1 个，第 9 行 9 个）
# 所以外层 i 从 1 到 9；内层 j 从 1 到 i（注意是 i+1 才能取到 i——含起不含止！）
for i in range(1, 10):                        # 行号 1-9
    row = ""                                  # 每行开头清空字符串，用拼接攒一行
    for j in range(1, i + 1):                 # 列号 1 到 i；range 不含止，所以要 i+1
        row += f"{j}*{i}={i * j}\t"           # \t 是制表符（Tab），让式子纵向对齐
    print(row)                                # 一行攒完再打印，而不是每个式子打一行

# ===== 5. 对照检查 =====
# 最后一行应该是：1×9=9  2×9=18  3×9=27  4×9=36  5×9=45  6×9=54  7×9=63  8×9=72  9×9=81
# 常见错误：内层写成 range(1, 10) 会打出满 9×9 的对称表（1×9 和 9×1 都出现）——不是错的，但不是标准九九表
